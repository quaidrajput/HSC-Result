#!/usr/bin/env python3
"""Build the final JS data bundle used by the website.

Scans data/groups/<group-id>/ folders, each containing exam.json,
results.json, colleges.json and withheld.json, and emits assets/js/data.js
as a single self-contained script with support for multiple exams/groups.

Works on GitHub Pages / any static host, no fetch needed.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GROUPS = ROOT / "data" / "groups"
OUT = ROOT / "assets" / "js" / "data.js"


def main() -> None:
    if not GROUPS.is_dir():
        raise SystemExit(f"Data groups folder not found: {GROUPS}")

    group_dirs = sorted([d for d in GROUPS.iterdir() if d.is_dir()])
    if not group_dirs:
        raise SystemExit(f"No exam groups found under {GROUPS}")

    def group_sort_key(d: Path) -> tuple:
        try:
            return (json.loads((d / "exam.json").read_text(encoding="utf-8")).get("order", 99), d.name)
        except Exception:
            return (99, d.name)

    group_dirs.sort(key=group_sort_key)

    exams = []
    total_records = 0
    total_colleges = 0
    total_withheld = 0

    for gdir in group_dirs:
        group_id = gdir.name

        def read(name: str):
            return json.loads((gdir / name).read_text(encoding="utf-8"))

        exam = read("exam.json")
        if "id" not in exam:
            exam["id"] = group_id
        results = read("results.json")
        colleges = read("colleges.json")
        withheld = read("withheld.json")

        # Build roll -> record index for O(1) lookup
        index = {}
        for i, rec in enumerate(results):
            index[rec["roll_number"]] = i

        exams.append({
            "id": exam["id"],
            "exam": exam,
            "results": results,
            "index": index,
            "colleges": colleges,
            "withheld": withheld,
        })

        total_records += len(results)
        total_colleges += len(colleges)
        total_withheld += sum(len(v) for v in withheld.values())
        print(f"  group: {group_id} | records: {len(results)} | colleges: {len(colleges)} | withheld: {sum(len(v) for v in withheld.values())}")

    bundle = {"exams": exams}

    OUT.parent.mkdir(parents=True, exist_ok=True)
    js = "// AUTO-GENERATED by tools/build_data.py -- do not edit.\n"
    js += "// Regenerate after updating gazette data: python tools/build_data.py\n"
    js += "window.BIEK_DATA = " + json.dumps(bundle, ensure_ascii=False, separators=(",", ":")) + ";\n"
    OUT.write_text(js, encoding="utf-8")

    print(f"Wrote {OUT.relative_to(ROOT)}")
    print(f"  groups: {len(exams)} | records: {total_records} | colleges: {total_colleges} | withheld: {total_withheld} | size: {OUT.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
